function updateAmbientFrame() {
  if (!ambientGlow) {
    return;
  }

  if (isPageScrolling) {
    requestAnimationFrame(updateAmbientFrame);
    return;
  }

  const width = window.innerWidth;
  const height = window.innerHeight;
  const idleX = width * 0.5 + Math.sin(Date.now() * 0.00018) * 28;
  const idleY = height * 0.42 + Math.cos(Date.now() * 0.00016) * 22;
  glowTargetX = hasPointer ? width * 0.5 + (pointerX - width * 0.5) * 0.18 : idleX;
  glowTargetY = hasPointer ? height * 0.42 + (pointerY - height * 0.42) * 0.14 : idleY;
  glowCurrentX += (glowTargetX - glowCurrentX) * 0.045;
  glowCurrentY += (glowTargetY - glowCurrentY) * 0.045;
  ambientGlow.style.transform = `translate3d(calc(${glowCurrentX}px - 50%), calc(${glowCurrentY}px - 50%), 0)`;

  requestAnimationFrame(updateAmbientFrame);
}


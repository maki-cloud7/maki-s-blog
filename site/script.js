(function initGridSVG() {
  const svg = document.getElementById("grid-overlay");
  if (!svg) return;
  const GRID_SIZE = 64;
  const BEND_RADIUS = 220;
  const MAX_BEND = 9;
  const STIFFNESS = 0.075;
  const DAMPING = 0.76;
  let mouseX = -500;
  let mouseY = -500;
  let width = 0;
  let height = 0;
  let gridFrame = 0;
  const lines = [];
  const NS = "http://www.w3.org/2000/svg";

  const defs = document.createElementNS(NS, "defs");
  const filter = document.createElementNS(NS, "filter");
  filter.setAttribute("id", "grid-glow");
  filter.setAttribute("x", "-50%");
  filter.setAttribute("y", "-50%");
  filter.setAttribute("width", "200%");
  filter.setAttribute("height", "200%");
  const blur = document.createElementNS(NS, "feGaussianBlur");
  blur.setAttribute("stdDeviation", "3.1");
  blur.setAttribute("result", "blur");
  filter.appendChild(blur);
  const composite = document.createElementNS(NS, "feComposite");
  composite.setAttribute("in", "SourceGraphic");
  composite.setAttribute("in2", "blur");
  composite.setAttribute("operator", "over");
  filter.appendChild(composite);
  defs.appendChild(filter);
  svg.appendChild(defs);

  const glowGroup = document.createElementNS(NS, "g");
  glowGroup.setAttribute("filter", "url(#grid-glow)");
  glowGroup.setAttribute("fill", "none");
  svg.appendChild(glowGroup);

  const lineGroup = document.createElementNS(NS, "g");
  lineGroup.setAttribute("fill", "none");
  svg.appendChild(lineGroup);

  const hGroup = document.createElementNS(NS, "g");
  hGroup.setAttribute("fill", "none");
  svg.appendChild(hGroup);

  function isDark() {
    return document.documentElement.dataset.theme === "dark";
  }

  function resize() {
    width = window.innerWidth;
    height = window.innerHeight;
    svg.setAttribute("viewBox", `0 0 ${width} ${height}`);
    svg.setAttribute("width", width);
    svg.setAttribute("height", height);
    hGroup.textContent = "";
    for (let y = 0; y <= height; y += GRID_SIZE) {
      const hLine = document.createElementNS(NS, "line");
      hLine.setAttribute("x1", 0);
      hLine.setAttribute("y1", y);
      hLine.setAttribute("x2", width);
      hLine.setAttribute("y2", y);
      hLine.setAttribute("stroke", isDark() ? "rgba(244,243,238,0.04)" : "rgba(16,16,16,0.035)");
      hLine.setAttribute("stroke-width", "1");
      hGroup.appendChild(hLine);
    }
    lineGroup.textContent = "";
    glowGroup.textContent = "";
    lines.length = 0;
    const count = Math.floor(width / GRID_SIZE) + 1;
    for (let i = 0; i < count; i++) {
      const x = i * GRID_SIZE;
      const line = document.createElementNS(NS, "path");
      line.setAttribute("d", `M ${x},0 L ${x},${height}`);
      line.setAttribute("stroke", isDark() ? "rgba(244,243,238,0.04)" : "rgba(16,16,16,0.035)");
      line.setAttribute("stroke-width", "1");
      lineGroup.appendChild(line);
      const glowLine = document.createElementNS(NS, "path");
      glowLine.setAttribute("d", `M ${x},0 L ${x},${height}`);
      glowLine.setAttribute("stroke", "rgba(179,42,37,0)");
      glowLine.setAttribute("stroke-width", "3");
      glowLine.setAttribute("stroke-linecap", "round");
      glowGroup.appendChild(glowLine);
      lines.push({
        x,
        offset: 0,
        velocity: 0,
        lastBend: 0,
        lineEl: line,
        glowEl: glowLine,
      });
    }
  }

  function updateLinePath(line, bend) {
    if (Math.abs(bend - line.lastBend) < 0.01) {
      return;
    }

    line.lastBend = bend;
    const x = line.x;
    const top = Math.max(0, mouseY - BEND_RADIUS);
    const bottom = Math.min(height, mouseY + BEND_RADIUS);
    let d;
    if (Math.abs(bend) < 0.05 || mouseY < -100) {
      d = `M ${x},0 L ${x},${height}`;
      line.glowEl.setAttribute("stroke", "rgba(179,42,37,0)");
      line.lineEl.setAttribute("stroke", isDark() ? "rgba(244,243,238,0.04)" : "rgba(16,16,16,0.035)");
    } else {
      const cpX = x + bend;
      d = `M ${x},0 L ${x},${top} Q ${cpX},${mouseY} ${x},${bottom} L ${x},${height}`;
      const bendRatio = Math.min(1, Math.abs(bend) / MAX_BEND);
      const glowAlpha = (bendRatio * 0.36).toFixed(3);
      line.glowEl.setAttribute("stroke", `rgba(179,42,37,${glowAlpha})`);
      line.lineEl.setAttribute("stroke", isDark() ? "rgba(244,243,238,0.085)" : "rgba(16,16,16,0.07)");
    }
    line.lineEl.setAttribute("d", d);
    line.glowEl.setAttribute("d", d);
  }

  function updateSprings() {
    const inRange = mouseX > -100 && mouseY > -100;
    let hasMotion = false;

    for (const line of lines) {
      let target = 0;
      if (inRange) {
        const dist = Math.abs(mouseX - line.x);
        if (dist < BEND_RADIUS) {
          const strength = 1 - dist / BEND_RADIUS;
          const eased = strength * Math.exp(-strength * 0.7);
          const direction = mouseX > line.x ? 1 : -1;
          target = eased * MAX_BEND * direction;
        }
      }
      const force = (target - line.offset) * STIFFNESS;
      line.velocity += force;
      line.velocity *= DAMPING;
      line.offset += line.velocity;
      if (Math.abs(line.offset) < 0.02 && Math.abs(target) < 0.02) {
        line.offset = 0;
        line.velocity = 0;
      }

      if (Math.abs(line.offset) > 0.02 || Math.abs(line.velocity) > 0.02 || Math.abs(target) > 0.02) {
        hasMotion = true;
      }

      if (!inRange && line.offset === 0 && line.velocity === 0) {
        updateLinePath(line, 0);
        continue;
      }

      updateLinePath(line, line.offset);
    }

    return hasMotion;
  }

  function drawFrame() {
    const hasMotion = updateSprings();
    if (hasMotion || (mouseX > -100 && mouseY > -100)) {
      gridFrame = requestAnimationFrame(drawFrame);
    } else {
      gridFrame = 0;
    }
  }

  function startGridFrame() {
    if (!gridFrame) {
      gridFrame = requestAnimationFrame(drawFrame);
    }
  }

  window.addEventListener("mousemove", (e) => {
    mouseX = e.clientX;
    mouseY = e.clientY;
    startGridFrame();
  });
  window.addEventListener("mouseleave", () => {
    mouseX = -500;
    mouseY = -500;
    startGridFrame();
  });
  window.addEventListener("resize", resize);
  resize();
})();

function createAnimatedToken(token, indexOffset) {
  if (/^\s+$/.test(token)) {
    const space = document.createElement("span");
    space.className = "word-space";
    space.setAttribute("aria-hidden", "true");
    return { element: space, nextIndex: indexOffset };
  }

  const tokenWrap = document.createElement("span");
  const isMaki = token.toLowerCase().replace(/[^\w]/g, "") === "maki";
  tokenWrap.className = isMaki ? "word-unit capsule-maki" : "word-unit";

  Array.from(token).forEach((char, charIndex) => {
    const charSpan = document.createElement("span");
    charSpan.className = "word-char";
    charSpan.style.setProperty("--char-index", String(indexOffset + charIndex));
    charSpan.textContent = char;
    tokenWrap.append(charSpan);
  });

  return { element: tokenWrap, nextIndex: indexOffset + Array.from(token).length };
}

